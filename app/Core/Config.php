<?php
declare(strict_types=1);

namespace M4W\Core;

/**
 * Static configuration (config/config.php). Runtime settings editable from the
 * admin console live in the database, see Settings.
 */
final class Config
{
    private static array $data = [];
    private static bool $installed = false;

    public static function path(): string
    {
        return getenv('M4W_CONFIG') ?: M4W_ROOT . '/config/config.php';
    }

    public static function load(): void
    {
        $defaults = [
            'debug'        => false,
            'timezone'     => 'Europe/Paris',
            'storage_path' => M4W_ROOT . '/storage',
            'db'           => ['driver' => 'sqlite', 'path' => M4W_ROOT . '/storage/data/m4w.sqlite'],
            'app_key'      => '',
            'base_url'     => '',
            'trusted_proxies' => [],
            'outbound_proxy' => '',
        ];
        $file = self::path();
        if (is_file($file)) {
            $cfg = require $file;
            if (is_array($cfg)) {
                self::$data = array_replace_recursive($defaults, $cfg);
                self::$installed = !empty(self::$data['app_key']);
                self::followMove($defaults);
                return;
            }
        }
        self::$data = $defaults;
    }

    /**
     * An installation copied or moved elsewhere keeps the paths of its old place in its
     * configuration (written that way by older installers): when they no longer exist and the
     * application's own folder holds the data, that one is used.
     */
    private static function followMove(array $defaults): void
    {
        $storage = (string) self::$data['storage_path'];
        if ($storage !== $defaults['storage_path'] && !is_dir($storage) && is_dir($defaults['storage_path'])) {
            self::$data['storage_path'] = $defaults['storage_path'];
        }
        $db = self::$data['db'];
        if (($db['driver'] ?? '') === 'sqlite' && ($db['path'] ?? '') !== $defaults['db']['path']) {
            $local = rtrim((string) self::$data['storage_path'], '/') . '/data/' . basename((string) $db['path']);
            if (!is_file((string) $db['path']) && is_file($local)) {
                self::$data['db']['path'] = $local;
            }
        }
    }

    public static function installed(): bool
    {
        return self::$installed;
    }

    public static function get(string $key, mixed $default = null): mixed
    {
        $node = self::$data;
        foreach (explode('.', $key) as $part) {
            if (!is_array($node) || !array_key_exists($part, $node)) {
                return $default;
            }
            $node = $node[$part];
        }
        return $node;
    }

    public static function all(): array
    {
        return self::$data;
    }

    public static function storagePath(string $sub = ''): string
    {
        $base = rtrim((string) self::get('storage_path', M4W_ROOT . '/storage'), '/');
        return $sub === '' ? $base : $base . '/' . ltrim($sub, '/');
    }

    /** Write a fresh config file (installer). */
    public static function write(array $cfg): void
    {
        $php = "<?php\n// Generated by the Make4WebMail installer on " . date('c') . "\n"
            . "// Keep this file private: it contains the application encryption key.\n"
            . 'return ' . var_export($cfg, true) . ";\n";
        $file = self::path();
        if (!is_dir(dirname($file))) {
            mkdir(dirname($file), 0750, true);
        }
        file_put_contents($file, $php, LOCK_EX);
        @chmod($file, 0640);
        self::load();
    }
}
